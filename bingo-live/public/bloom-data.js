export const uid = () => globalThis.crypto?.randomUUID?.() || Date.now().toString(36) + Math.random().toString(36).slice(2);

export function createBoard(key = 'cozy', size = 3, title = '') {
  const t = templates[key] || templates.cozy,
    list = key === 'blank' ? [] : t.tasks.split('\n');
  return {
    id: uid(),
    title: title.trim() || (key === 'blank' ? 'Новая доска' : t.title),
    subtitle: key === 'blank' ? 'Личные задачи и награды в вашем ритме.' : t.subtitle,
    template: key,
    size,
    bonus: key === 'blank' ? 'Вечер для себя' : t.bonus,
    theme: 'matcha',
    animation: 'scratch',
    started: false,
    startedAt: null,
    boardSeed: uid(),
    durationLabel: t.period,
    calendarStart: new Date().toISOString(),
    calendarHidden: false,
    cover: 'glasshouse',
    harvest: [],
    legacyLines: [],
    created: Date.now(),
    cells: Array.from({
      length: size * size
    }, (_, i) => ({
      id: uid(),
      task: list[i] || '',
      reward: list[i] ? rewards[(i * 7 + 6) % rewards.length] : '',
      icon: artNames[i % artNames.length],
      color: i % 9,
      done: 0
    }))
  };
}

export function allLines(board) {
  const n = board.size,
    seq = Array.from({
      length: n
    }, (_, i) => i);
  const rows = seq.map(r => seq.map(c => r * n + c)),
    cols = seq.map(c => seq.map(r => r * n + c));
  return [...rows, ...cols, seq.map(i => i * (n + 1)), seq.map(i => (i + 1) * (n - 1))];
}

export function lineIds(board) {
  return allLines(board).filter(line => line.every(i => board.cells[i].done));
}

export function resizeBoard(b, size) {
  if (b.size === size || ![3, 4, 5].includes(size)) return;
  // Enumerate outer rings in a fixed order so hidden cells keep their coordinates.
  const positions = Array.from({length: 25}, (_, i) => ({x: i % 5, y: Math.floor(i / 5)}))
    .sort((a, b) => Math.max(a.x, a.y) - Math.max(b.x, b.y));
  const slots = new Map();
  const reserve = [...(b.overflow || [])];
  for (const {x, y} of positions) {
    const cell = x < b.size && y < b.size ? b.cells[y * b.size + x] : reserve.shift();
    if (cell) slots.set(y * 5 + x, cell);
  }
  const known = new Set([...slots.values()].map(cell => cell.task));
  const key = b.started && b.template === 'blank' ? 'cozy' : b.template;
  const pool = createBoard(key, 5).cells.filter(cell => !cell.task || !known.has(cell.task));
  const visible = Array(size * size), hidden = [];
  for (const {x, y} of positions) {
    const cell = slots.get(y * 5 + x);
    if (x < size && y < size) {
      const shown = cell || pool.shift();
      if (b.started && !shown.task) shown.task = pool.shift().task;
      if (b.started && !shown.reward) shown.reward = rewards[(y * size + x) % rewards.length];
      visible[y * size + x] = shown;
    }
    else if (cell) hidden.push(cell);
  }
  b.cells = visible;
  b.size = size;
  b.overflow = hidden;
}

export function shuffleBoard(b) {
  for (let i = b.cells.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [b.cells[i], b.cells[j]] = [b.cells[j], b.cells[i]];
  }
}
